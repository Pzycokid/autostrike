"""Write the engagement as JSON, Markdown and a self-contained HTML report."""
from __future__ import annotations

import html
import json
from collections import Counter
from pathlib import Path

from autostrike import __version__
from autostrike.models import Engagement
from autostrike.phases import SEVERITY_ORDER, load_json

PHASE_TECHNIQUES = {"recon": "T1595.001", "enumeration": "T1046"}


def attack_rows(eng: Engagement) -> list[tuple[str, str, str, int]]:
    """(technique, name, tactic, count) for every technique the engagement touched."""
    db = load_json("attack.json")
    counts: Counter[str] = Counter()
    for p in eng.phases:
        if p.name in PHASE_TECHNIQUES:
            counts[PHASE_TECHNIQUES[p.name]] += 1
    counts.update(f.technique for f in eng.findings)
    counts.update(s.technique for s in eng.post_plan)
    rows = []
    for tech, n in counts.items():
        meta = db.get(tech, {"name": "unknown", "tactic": "unknown"})
        rows.append((tech, meta["name"], meta["tactic"], n))
    tactic_order = ["Reconnaissance", "Discovery", "Initial Access", "Credential Access",
                    "Lateral Movement", "Persistence", "Collection"]
    rows.sort(key=lambda r: (tactic_order.index(r[2]) if r[2] in tactic_order else 99, r[0]))
    return rows


def severity_counts(eng: Engagement) -> dict[str, int]:
    c = Counter(f.severity for f in eng.findings)
    return {s: c.get(s, 0) for s in sorted(SEVERITY_ORDER, key=SEVERITY_ORDER.get)}


def render_markdown(eng: Engagement) -> str:
    sev = severity_counts(eng)
    out = [
        f"# Auto Strike report: {eng.name}",
        "",
        f"- **Mode:** {eng.mode}  ",
        f"- **Scope:** {', '.join(eng.scope)}  ",
        f"- **Live hosts:** {len(eng.hosts)} | **Findings:** {len(eng.findings)} "
        f"({', '.join(f'{k} {v}' for k, v in sev.items() if v)})",
        "",
        "## Kill chain",
        "",
        "| # | Phase | Summary |",
        "|---|---|---|",
    ]
    out += [f"| {i} | {p.name} | {p.summary} |" for i, p in enumerate(eng.phases, 1)]
    out += ["", "## Hosts", "", "| Host | Name | OS guess | Open services |", "|---|---|---|---|"]
    for h in eng.hosts:
        svcs = ", ".join(
            f"{s.port}/{s.name}" + (f" ({s.product} {s.version})".replace(" )", ")") if s.product else "")
            for s in h.services
        )
        out.append(f"| {h.ip} | {h.hostname or '-'} | {h.os_guess or '-'} | {svcs or '-'} |")
    out += ["", "## Findings", ""]
    if not eng.findings:
        out.append("No findings.")
    for i, f in enumerate(eng.findings, 1):
        out += [
            f"### {i}. [{f.severity.upper()}] {f.title}",
            "",
            f"- **Host:** {f.host}:{f.port}",
            f"- **CVE:** {f.cve or 'n/a'} | **ATT&CK:** {f.technique}",
            f"- **Evidence:** `{f.evidence}`",
            f"- **Why it matters:** {f.description}",
            f"- **Fix:** {f.remediation}",
            "",
        ]
    out += ["## Simulated post-exploitation plan", "",
            "_Planned only. Auto Strike never executes these steps._", ""]
    if eng.post_plan:
        out += ["| Foothold | # | Tactic | Technique | Action |", "|---|---|---|---|---|"]
        out += [f"| {s.host} | {s.order} | {s.tactic} | {s.technique} | {s.action} |" for s in eng.post_plan]
    else:
        out.append("No critical or high footholds, so no plan was generated.")
    out += ["", "## MITRE ATT&CK coverage", "", "| Technique | Name | Tactic | Hits |", "|---|---|---|---|"]
    out += [f"| {t} | {n} | {tac} | {c} |" for t, n, tac, c in attack_rows(eng)]
    out += ["", f"_Generated by Auto Strike {__version__}. For authorised lab use only._", ""]
    return "\n".join(out)


CSS = """
body{font-family:system-ui,Segoe UI,Arial,sans-serif;margin:2rem auto;max-width:1100px;padding:0 1rem;color:#1c2330;background:#fff}
h1{font-size:1.6rem}h2{margin-top:2rem;border-bottom:2px solid #e3e7ee;padding-bottom:.3rem}
table{border-collapse:collapse;width:100%;font-size:.92rem}th,td{border:1px solid #d9dee7;padding:.45rem .6rem;text-align:left;vertical-align:top}
th{background:#f3f5f9}.sev{font-weight:700;padding:.1rem .45rem;border-radius:4px;color:#fff}
.critical{background:#b42318}.high{background:#c4320a}.medium{background:#b54708}.low{background:#3e7c17}.info{background:#475467}
.cards{display:flex;gap:1rem;flex-wrap:wrap}.card{border:1px solid #d9dee7;border-radius:8px;padding:.8rem 1rem;min-width:120px}
.card b{display:block;font-size:1.5rem}code{background:#f3f5f9;padding:.05rem .3rem;border-radius:3px}.note{color:#667085}
"""


def render_html(eng: Engagement) -> str:
    e = html.escape
    sev = severity_counts(eng)
    cards = "".join(f'<div class="card"><b>{v}</b>{e(k)}</div>' for k, v in sev.items())
    phases = "".join(f"<tr><td>{i}</td><td>{e(p.name)}</td><td>{e(p.summary)}</td></tr>"
                     for i, p in enumerate(eng.phases, 1))
    hosts = "".join(
        f"<tr><td>{e(h.ip)}</td><td>{e(h.hostname or '-')}</td><td>{e(h.os_guess or '-')}</td><td>"
        + e(", ".join(f"{s.port}/{s.name} {s.product} {s.version}".strip() for s in h.services)) + "</td></tr>"
        for h in eng.hosts
    )
    findings = "".join(
        f'<tr><td><span class="sev {e(f.severity)}">{e(f.severity)}</span></td><td>{e(f.title)}</td>'
        f"<td>{e(f.host)}:{f.port}</td><td>{e(f.cve or 'n/a')}</td><td>{e(f.technique)}</td>"
        f"<td><code>{e(f.evidence)}</code><br>{e(f.remediation)}</td></tr>"
        for f in eng.findings
    )
    plan = "".join(
        f"<tr><td>{e(s.host)}</td><td>{s.order}</td><td>{e(s.tactic)}</td><td>{e(s.technique)}</td><td>{e(s.action)}</td></tr>"
        for s in eng.post_plan
    )
    attack = "".join(f"<tr><td>{e(t)}</td><td>{e(n)}</td><td>{e(tac)}</td><td>{c}</td></tr>"
                     for t, n, tac, c in attack_rows(eng))
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>Auto Strike report</title>
<style>{CSS}</style></head><body>
<h1>Auto Strike report: {e(eng.name)}</h1>
<p class="note">Mode: {e(eng.mode)} &middot; Scope: {e(', '.join(eng.scope))} &middot; {len(eng.hosts)} live host(s)</p>
<div class="cards">{cards}</div>
<h2>Kill chain</h2><table><tr><th>#</th><th>Phase</th><th>Summary</th></tr>{phases}</table>
<h2>Hosts</h2><table><tr><th>Host</th><th>Name</th><th>OS guess</th><th>Open services</th></tr>{hosts}</table>
<h2>Findings</h2><table><tr><th>Severity</th><th>Title</th><th>Target</th><th>CVE</th><th>ATT&amp;CK</th><th>Evidence / fix</th></tr>{findings}</table>
<h2>Simulated post-exploitation plan</h2><p class="note">Planned only. Auto Strike never executes these steps.</p>
<table><tr><th>Foothold</th><th>#</th><th>Tactic</th><th>Technique</th><th>Action</th></tr>{plan}</table>
<h2>MITRE ATT&amp;CK coverage</h2><table><tr><th>Technique</th><th>Name</th><th>Tactic</th><th>Hits</th></tr>{attack}</table>
<p class="note">Generated by Auto Strike {__version__}. For authorised lab use only.</p>
</body></html>
"""


def write_reports(eng: Engagement, outdir) -> list[Path]:
    out = Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    paths = [out / "report.json", out / "report.md", out / "report.html"]
    paths[0].write_text(json.dumps({**eng.to_dict(), "attack_coverage": attack_rows(eng)}, indent=2), encoding="utf-8")
    paths[1].write_text(render_markdown(eng), encoding="utf-8")
    paths[2].write_text(render_html(eng), encoding="utf-8")
    return paths
